"""Reproduce HP RADV hardware properties from the checked-in live Linux capture.

Never imports Linux VA layout, heap budgets, firmware versions or readiness flags.
"""
import argparse
import json
from pathlib import Path
from phx_profile import ROOT, PROFILE, load, integer, validate

CAPTURE = ROOT/'hardware/dumps/hp_envy_760m/linux-2026-11-08.json'
HEADER = ROOT/'src/amd/phx_hp_760m_device.h'
FIELDS = ('chip_rev','external_rev','family','gpu_counter_freq','max_engine_clock','max_memory_clock',
          'vram_type','vram_bit_width','num_hw_gfx_contexts','wave_front_size','num_shader_visible_vgprs',
          'num_tcc_blocks','gs_vgt_table_depth','gs_prim_buffer_depth','max_gs_waves_per_vgt',
          'gc_double_offchip_lds_buf','pa_sc_tile_steering_override','tcc_disabled_mask',
          'tcp_cache_size','num_sqc_per_wgp','sqc_data_cache_size','sqc_inst_cache_size',
          'gl1c_cache_size','gl2c_cache_size','mall_size')

def render(capture):
    profile = load(PROFILE)
    validate(capture['profile'])
    if capture['pci'] != profile['pci'] or capture['profile'] != profile:
        raise ValueError('live topology differs from supplied HP profile')
    d = capture['device_info']
    if d['device_id'] != profile['pci']['device'] or d['pci_rev'] != profile['pci']['revision']:
        raise ValueError('DRM and PCI identity disagree')
    values = [integer(d[k],0,(1<<64)-1 if k in ('max_engine_clock','max_memory_clock','tcc_disabled_mask','mall_size')
                      else (1<<32)-1,k) for k in FIELDS]
    if not d['gpu_counter_freq'] or not d['max_engine_clock'] or not d['max_memory_clock']:
        raise ValueError('missing measured clock capabilities')
    assignments = '\n'.join(f'    di->{k} = {v}ull;' for k,v in zip(FIELDS,values))
    return '''/* SPDX-License-Identifier: MIT
 * Generated by tools/phx_device_profile.py from live Linux capture 2026-11-08.
 * Exact HP profile only. Clock limits are captured caps, not current clock state.
 * No VA ranges, memory budgets, Linux flags, firmware state or readiness imported.
 * Include after the DRM device-info structure definition.
 */
#ifndef PHX_HP_760M_DEVICE_H
#define PHX_HP_760M_DEVICE_H
static inline void phx_hp_760m_apply_device_info(struct drm_amdgpu_info_device *di) {
''' + assignments + '\n}\n#endif\n'

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--write-header',action='store_true')
    a=ap.parse_args()
    try:
        content=render(json.loads(CAPTURE.read_text()))
        if a.write_header: HEADER.write_text(content)
        elif HEADER.read_text()!=content: raise ValueError('stale device properties header')
        print('HP measured device properties match; native execution remains gated')
    except (ValueError,KeyError,TypeError,OSError) as e: ap.exit(1,f'device profile: {e}\n')

if __name__=='__main__': main()
